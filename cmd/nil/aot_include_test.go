// A project that calls C writes a C file, that file includes the header `nil header`
// generated, and the build compiles it. Every one of those three facts was true and
// the thing still did not work, twice:
//
//	l57demo.h: No such file or directory
//	nilffi.h:   No such file or directory
//
// Both are the same bug wearing two hats — an include path that was not passed — and
// both reached the user as a compiler error naming a file they had never written,
// about a header generated by a command they had run correctly.
//
// So the contract is stated here as a test rather than left to the three commands to
// agree about.

// programForHeader builds a program through the real front end.
//
// The header's contents depend on the program's declarations, and a header assembled
// by hand would agree with whatever the test expected — which is the thing this file
// is not testing.
func programForHeader(t *testing.T, source string) *mir.Program {
	t.Helper()

	checked := frontend.Check(source, frontend.Options{})
	if !checked.OK {
		t.Fatalf("the program was rejected: %s", checked.ErrSummary())
	}
	optimized := hir.NewOptimizer().Optimize(hir.NewLowerer().LowerProgram(checked.Lowered))
	return mir.NewLowerer().LowerHIR(optimized)
}

// TestTheGeneratedHeaderIsReachableFromAProjectCFile is the whole contract.
//
// Not "the paths look right": the generated header is produced, every `#include` in it
// is followed, and the answer is whether a C file could actually open it. That is the
// question a user is asking when they write `#include "theirproject.h"`.
func TestTheGeneratedHeaderIsReachableFromAProjectCFile(t *testing.T) {
	outputDir := t.TempDir()

	header, err := cheader.Generate(programForHeader(t, `
		struct Point { x: Int, y: Int }
		extern "C" fn measure(p: Point) -> Int;
		measure(Point { x: 1, y: 2 });
	`), "theirproject")
	if err != nil {
		t.Fatalf("generating the header failed: %v", err)
	}

	if err := os.WriteFile(filepath.Join(outputDir, "theirproject.h"), []byte(header), 0o644); err != nil {
		t.Fatal(err)
	}

	// Every `#include "..."` in the generated header must resolve against the flags
	// the build actually passes. The two C-standard headers are the compiler's own;
	// the rest are this project's and the runtime's.
	includes := projectCIncludes(outputDir)
	for _, line := range strings.Split(header, "\n") {
		if !strings.HasPrefix(line, "#include \"") {
			continue
		}
		name := line[len("#include \""):]
		name = name[:strings.Index(name, "\"")]

		resolved := false
		for index := 0; index+1 < len(includes); index++ {
			if includes[index] != "-I" {
				continue
			}
			if _, err := os.Stat(filepath.Join(includes[index+1], name)); err == nil {
				resolved = true
				break
			}
		}
		if !resolved {
			t.Errorf("the generated header includes %q and no -I in %v contains it", name, includes)
		}
	}
}

// TestTheOutputDirectoryIsOnTheIncludePath is the first of the two, on its own.
//
// Because it is the one that looks right: the compiler *is* pointed at the project
// directory, the header *is* in `build/`, and the include path says otherwise.
func TestTheOutputDirectoryIsOnTheIncludePath(t *testing.T) {
	includes := projectCIncludes(filepath.Join("some", "project", "build"))
	if includes[0] != "-I" || includes[1] != filepath.Join("some", "project", "build") {
		t.Errorf("the build directory is not the first include: %v", includes)
	}
}

// TestTheGeneratedHeaderActuallyIncludesNilFFI checks the premise of the test above.
//
// A header that included nothing would make `TestTheGeneratedHeaderIsReachable…`
// pass vacuously. This uses the real generator, so the two together are an argument
// rather than a tautology.
func TestTheGeneratedHeaderActuallyIncludesNilFFI(t *testing.T) {
	program := programForHeader(t, `
		struct Point { x: Int, y: Int }
		extern "C" fn measure(p: Point) -> Int;
		measure(Point { x: 1, y: 2 });
	`)

	header, err := cheader.Generate(program, "theirproject")
	if err != nil {
		t.Fatalf("generating the header failed: %v", err)
	}
	if !strings.Contains(header, `#include "nilffi.h"`) {
		t.Errorf("the generated header does not include nilffi.h, so the reachability "+
			"test above proves nothing:\n%s", header)
	}
}

// TestTheRuntimeHeadersAreWhereTheBuildSaysTheyAre closes the loop.
//
// `nilcore` is the single place that knows where the runtime's headers are. If the
// build's include paths and `nilcore` disagreed, every project C file that included
// the generated header would fail on a machine where the runtime built perfectly well.
func TestTheRuntimeHeadersAreWhereTheBuildSaysTheyAre(t *testing.T) {
	includes := projectCIncludes(t.TempDir())

	for _, header := range []struct {
		name string
		dir  string
	}{
		{"nil.h", nilcore.IncludeDir()},
		{"nilffi.h", nilcore.FFIDir()},
	} {
		if _, err := os.Stat(filepath.Join(header.dir, header.name)); err != nil {
			t.Errorf("the build puts %s on the include path, but %s does not contain it",
				header.name, header.dir)
		}
		found := false
		for _, path := range includes {
			if path == header.dir {
				found = true
			}
		}
		if !found {
			t.Errorf("%s is not on the include path a project C file is compiled with: %v",
				header.name, includes)
		}
	}
}
