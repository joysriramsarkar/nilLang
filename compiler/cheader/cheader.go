// Package cheader writes a C header for a Nilang program's foreign declarations.
//
// # What this is for
//
// A program that calls C has written declarations for functions somebody else
// implements. The C side then has to guess the other half: what the parameters
// really are, whether a string is one pointer or two, where the answer to a
// function that returns a string goes, and who is allowed to free what.
//
// Today the answer is "read `nilffi.h`". That file says what the *boundary* is;
// it does not say what *this program* declared. The gap is where C code gets
// written against the wrong signature, and it is silent — it compiles, links, and
// reads a length out of a pointer.
//
// # Why it is generated and not written
//
// Because a hand-written header is a second copy of the declarations, and a second
// copy drifts. The day `String` stops crossing as two arguments, the hand-written
// header keeps saying two, and the program that uses it reads a length out of a
// pointer — with no diagnostic anywhere, because both copies were once right.
//
// So this reads the same crossing table the emitter reads. The prototype it writes
// and the `declare` the module carries come from one `Crossing`, and a test
// compares them.
//
// # Why it is discardable
//
// Because it is derived, not owned. Nothing reads it that could not regenerate it,
// and editing it is wasted work that the next build silently undoes. A header that
// had to be kept in step by hand would be a second source of truth, which is the
// thing this exists to avoid.
package cheader

import (
	"fmt"
	"sort"
	"strings"

	"github.com/joysriramsarkar/nilLang/compiler/ffi"
	"github.com/joysriramsarkar/nilLang/compiler/mir"
)

// Generate writes the C header for every `extern "C"` a program declares.
//
// The result is always a complete, compilable header — including when the program
// declares nothing, which is the case a reader is most likely to be confused by: an
// empty file looks like a failed build rather than an answer.
func Generate(program *mir.Program, projectName string) (string, error) {
	var b strings.Builder

	guard := guardName(projectName)
	fmt.Fprintf(&b, "/* %s.h — generated by `nil header`. Do not edit.\n", projectName)
	b.WriteString(" *\n")
	b.WriteString(" * Regenerate it rather than changing it: it is derived from the same crossing\n")
	b.WriteString(" * table the compiler emits its calls from, so a change made here would be\n")
	b.WriteString(" * undone by the next build without saying so.\n")
	b.WriteString(" */\n")
	fmt.Fprintf(&b, "#ifndef %s\n#define %s\n\n", guard, guard)
	b.WriteString("#include <stddef.h>\n#include <stdint.h>\n\n")
	b.WriteString("#include \"nilffi.h\"\n\n")

	names, err := foreignNames(program)
	if err != nil {
		return "", err
	}

	writeStructTypes(&b, program)
	if len(names) == 0 {
		fmt.Fprintf(&b, "/* %s declares no `extern \"C\"` functions, so this header has nothing\n", projectName)
		b.WriteString(" * to declare. It is written anyway so that including it is never an error.\n")
		b.WriteString(" */\n")
	}

	for _, name := range names {
		fn := program.Functions[name]
		signature, err := ffi.SignatureFor(program, fn)
		if err != nil {
			return "", err
		}
		writeDeclaration(&b, fn, signature)
	}

	fmt.Fprintf(&b, "\n#endif /* %s */\n", guard)
	return b.String(), nil
}

// writeStructTypes declares each struct that crosses, as a C struct.
//
// # Why the header declares it rather than leaving the reader to write it
//
// Because the reader cannot. The offsets are the ones *our* layout computed and the
// ones a C compiler would compute for the same fields — and a reader who writes
// `struct Point { int64_t x; int64_t y; }` by hand gets the right thing by luck,
// while one who writes the fields in a different order gets a buffer C reads at the
// wrong offsets, silently, for as long as the program runs.
//
// So the type is generated, from the same layout the module's stores were written
// from. C includes the header and gets the struct the program actually has.
//
// Every struct the program declared is written, not only the ones a crossing
// mentions: a header is read by somebody who has not read the extern declarations,
// and a type missing from it is a type they cannot name.
func writeStructTypes(b *strings.Builder, program *mir.Program) {
	for _, name := range ffi.StructNames(program) {
		layout, err := ffi.LayoutOf(program, name)
		if err != nil {
			// Already refused by the signature, which names the field. Writing
			// nothing here rather than a broken typedef keeps the header's error in
			// one place instead of two.
			continue
		}

		fmt.Fprintf(b, "/* %s: %d byte(s), %d-byte aligned.\n", layout.Name, layout.Size, layout.Alignment)
		fmt.Fprintf(b, " * The offsets are the ones the compiler emitted the stores at, and the\n")
		fmt.Fprintf(b, " * ones a C compiler gives these fields. Do not reorder them. */\n")
		fmt.Fprintf(b, "typedef struct %s {\n", cTypeName(layout.Name))
		for _, field := range layout.Fields {
			if field.Crossing.Splat {
				// A string is two C members, pointer then length, eight bytes apart —
				// which is what `nil_string_unbox` writes and what the stores put
				// there.
				fmt.Fprintf(b, "  const char *%s;\n", field.Name)
				fmt.Fprintf(b, "  size_t %s_len;\n", field.Name)
				continue
			}
			fmt.Fprintf(b, "  %s %s;\n", cHeaderType(field.Crossing), field.Name)
		}
		fmt.Fprintf(b, "} %s;\n\n", cTypeName(layout.Name))
	}
}

// cTypeName is the C spelling of a struct a program declared.
//
// # Why the `_t`
//
// Because a C file that declares its own `Point` and then includes this header has a
// redefinition, and the reader's first mistake should not be a compiler error about
// a name collision. `_t` is not always enough — it is only the difference between a
// collision they can see and one they have to work out.
//
// # Why the suffix lives *here* and is not added at each use
//
// Because it was added at each use, and one of the uses forgot. The typedef said
// `Point_t` and the prototype said `Point`, and a C compiler answered "unknown type
// name 'Point'; did you mean 'Point_t'?" — which is the best error a C compiler
// produces and entirely avoidable. One function that returns the whole name cannot
// be used incorrectly; three `+ "_t"` expressions can.
func cTypeName(name string) string {
	return name + "_t"
}

// writeDeclaration writes one function's prototype, with the notes a C author would
// otherwise have to go and find.
//
// The notes are not decoration. Each one is a rule that is enforced at run time and
// produces no diagnostic when broken: a string that is not NUL-terminated, a
// buffer freed too early, an answer built with `malloc` that nobody will ever free.
// A reader who has the rules in front of them does not have to remember them.
func writeDeclaration(b *strings.Builder, fn *mir.Function, signature ffi.Signature) {
	params, notes := parameterList(fn, signature)

	result := cHeaderType(signature.Ret)
	if signature.Ret.Splat {
		// A string comes back through the caller's struct rather than as a value,
		// so the function returns nothing. See `nilffi.h` on why nothing here
		// returns a struct.
		result = "void"
	}

	fmt.Fprintf(b, "%s %s(%s);\n", result, fn.Name, strings.Join(params, ", "))
	for _, note := range notes {
		for _, line := range wrap(note, 72) {
			fmt.Fprintf(b, "/* %s */\n", line)
		}
	}
	b.WriteString("\n")
}

// parameterList writes the C parameter list, and the notes that go with it.
//
// Every parameter is **named**, because a parameter with no name is not a parameter
// in C — `void register(NilFFICallback);` declares a variable called
// `NilFFICallback`, and the compiler rejects the whole header with "variable or
// field 'NilFFICallback' declared void". That is the version this wrote first, and
// it is why the names are not optional decoration: a header's parameter names are
// the difference between a prototype and a syntax error.
//
// The names come from the Nilang declaration, so the C reader sees the names the
// program uses rather than `arg0, arg1`. Where a name cannot be printed — a keyword,
// or an annotation that never had one — it becomes `argN`, because a name that is
// readable matters and a name that compiles matters more.
func parameterList(fn *mir.Function, signature ffi.Signature) (params []string, notes []string) {
	borrowed := false
	position := 0
	counter := 0
	taken := map[string]bool{}

	// unique keeps a name nobody in this prototype is already using.
	//
	// Not hypothetical: a program can declare `fn f(text: String, text_len: Int)`,
	// and the derived `text_len` would collide with the real one. C answers
	// "redefinition of parameter", naming neither the string nor the parameter whose
	// name was already spoken for.
	unique := func(candidate string) string {
		for taken[candidate] {
			counter++
			candidate = fmt.Sprintf("arg%d", counter-1)
		}
		taken[candidate] = true
		return candidate
	}

	// baseName takes the next Nilang parameter's name, or invents one.
	//
	// Separate from `unique` because a *string* becomes two C parameters from **one**
	// Nilang parameter, and a single function taking a suffix cannot tell "derive the
	// length's name from this parameter" from "take the next parameter's name". It
	// did the latter: `fn f(text: String, count: Int)` declared
	// `f(const char *text, size_t count_len, int64_t count)`, so C read a length out
	// of a variable the caller never passed — and the header compiled.
	baseName := func() string {
		candidate := ""
		if position < len(fn.Params) {
			candidate = ffi.CIdentifier(fn.Params[position], "")
		}
		position++
		if candidate == "" {
			counter++
			return unique(fmt.Sprintf("arg%d", counter-1))
		}
		return unique(candidate)
	}

	for _, crossing := range signature.Params {
		// One Nilang parameter, whatever it becomes in C. A string is two C
		// parameters and must still consume one name from the declaration.
		field := baseName()

		if crossing.Splat {
			params = append(params,
				declare(cHeaderType(crossing), field),
				declare("size_t", unique(field+"_len")))
			borrowed = true
			continue
		}
		params = append(params, declare(cHeaderType(crossing), field))
	}

	if signature.Ret.Splat {
		// Last, and always: a C function may take arguments after the ones the
		// program converted, and the generated header is the only place a reader
		// learns that the answer goes in the final parameter.
		params = append(params, "NilFFIString *out")
	}

	// `void` rather than empty parentheses, because `f()` in C means "any
	// arguments" and `f(void)` means none. A header that says `f()` promises
	// something the generated module does not deliver.
	if len(params) == 0 {
		params = []string{"void"}
	}

	if borrowed {
		notes = append(notes,
			"A String argument is a (pointer, length) pair. The length is in BYTES,",
			"not characters, and the bytes are NOT NUL-terminated — a string may",
			"contain a NUL, so strlen() would answer the wrong thing.")
	}
	if signature.Ret.Splat {
		notes = append(notes,
			"The answer goes in *out. Fill it with nil_ffi_buffer(n): the runtime",
			"reclaims that when the call returns, so you do not free it and must not.",
			"An answer you already own — a static string, a table entry, or the",
			"pointer you were handed — is handed over unchanged and left alone.")
	}
	return params, notes
}

// cHeaderType is a crossing's C spelling, as this header writes it.
//
// # Why a struct's type is rewritten here rather than stored on the crossing
//
// Because `Crossing.C` is `const Point *` — the *conceptual* type — while the header
// declares `Point_t`. The suffix is a decision this file makes, so this file is where
// it is applied; putting it on the crossing would put a header convention in the
// package that knows nothing about headers, and the emitter would carry a name it
// never prints.
//
// The first version got this wrong by printing `const Point *` beside a typedef
// called `Point_t`, and a C compiler answered "unknown type name 'Point'; did you
// mean 'Point_t'?" — which is the best possible error and entirely avoidable.
func cHeaderType(crossing ffi.Crossing) string {
	if crossing.Struct == nil {
		return crossing.C
	}
	return "const " + cTypeName(crossing.Struct.Name) + " *"
}

// declare writes one C parameter as `type name`.
//
// A pointer binds to its name with no space — `const char *name`, not
// `const char * name`. The second is legal and every style guide rejects it, but the
// reason to get it right here is that the generated header is *read* by people, and
// a header full of `* name` is one people learn to skim.
func declare(cType, name string) string {
	if strings.HasSuffix(cType, "*") {
		return cType + name
	}
	return cType + " " + name
}

// foreignNames returns every foreign function's name, in a stable order.
//
// Sorted, so two runs of the same program produce the same bytes. Map order would
// make the header differ between runs for no reason a reader could see, which is
// the same reason the rest of the module's ordered output is sorted.
func foreignNames(program *mir.Program) ([]string, error) {
	names := make([]string, 0, len(program.Functions))
	for name, fn := range program.Functions {
		if fn != nil && fn.Foreign {
			names = append(names, name)
		}
	}
	sort.Strings(names)

	// Checked here rather than at the call site, because a header is read by
	// somebody who has never seen the program. A prototype for a type with no
	// crossing would be a guess, and a guess in a header is a guess nobody checks.
	for _, name := range names {
		if _, err := ffi.SignatureFor(program, program.Functions[name]); err != nil {
			return nil, err
		}
	}
	return names, nil
}

// guardName turns a project name into an include guard.
//
// Uppercased and stripped of anything that is not a letter, a digit or an
// underscore, because a project called `my-app` must not produce
// `#ifndef MY-APP` — which is not a valid identifier and is rejected at the point
// somebody includes the file, with a message about a token they cannot see.
func guardName(project string) string {
	var b strings.Builder
	b.WriteString("NILANG_")
	for _, r := range project {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z':
			// Only letters are folded. Doing the fold unconditionally turned a digit
			// into a control character — `'1' - 32` is `0x11` — so a project named
			// `123` produced a guard containing bytes no editor would show.
			b.WriteRune(r - 32)
		case r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	if b.Len() == len("NILANG_") {
		b.WriteString("GENERATED")
	}
	b.WriteString("_H")
	return b.String()
}

// wrap breaks a note into lines no longer than `width`.
//
// Written rather than left to a word-wrap library because the notes are already
// written as sentences, and a wrapper that re-flowed them would produce a different
// header on every platform it ran on.
func wrap(text string, width int) []string {
	words := strings.Fields(text)
	if len(words) == 0 {
		return nil
	}

	var lines []string
	current := words[0]
	for _, word := range words[1:] {
		if len(current)+1+len(word) > width {
			lines = append(lines, current)
			current = word
			continue
		}
		current += " " + word
	}
	return append(lines, current)
}
