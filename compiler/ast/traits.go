package ast

import (
	"bytes"

	"github.com/joysriramsarkar/nilLang/compiler/token"
)

// Traits and implementations.
//
// # Why a trait method is an ordinary function
//
// `impl` does not introduce a runtime dispatch table. Each method becomes an
// ordinary top-level function under a mangled name, and a call is rewritten to
// call it. Three things fall out of that, and all three are why it was chosen
// over a method table:
//
//   - The two engines need no change at all. They already call functions, so they
//     cannot disagree about how a method works.
//   - There is no vtable, no per-object type tag, and no cost at run time.
//   - The receiver's *static* type picks the implementation, which is the whole
//     point of a trait: a method call that resolved on the dynamic type would be
//     a different language, and one that resolved on nothing would be a runtime
//     failure instead of a diagnostic.
//
// # What is not here
//
// Static methods (`Type.new()`) and generic traits are not modelled. A static
// method needs a namespace form the language has no syntax for, and generics
// need a type system they can constrain; both are L2 work rather than something
// to half-add here.

// TraitDecl is `trait Name { methods }`.
//
// The body lists the methods an implementation must provide. It carries no
// bodies: a trait says what an implementation owes, and duplicating a default
// body in the declaration would mean two places to read and no way to know which
// one an implementation actually ran.
type TraitDecl struct {
	Token   token.Token // token.TRAIT
	Name    *Identifier
	Methods []*TraitMethod

	Body *BlockStatement // the raw body, kept so a formatter can round-trip it
}

func (td *TraitDecl) statementNode()       {}
func (td *TraitDecl) TokenLiteral() string { return td.Token.Literal }
func (td *TraitDecl) String() string {
	var out bytes.Buffer
	out.WriteString("trait " + td.Name.String() + " { ")
	for i, m := range td.Methods {
		if i > 0 {
			out.WriteString("; ")
		}
		out.WriteString(m.String())
	}
	return out.String() + " }"
}

// TraitMethod is one method signature in a trait or impl block.
type TraitMethod struct {
	Token      token.Token // token.FN
	Name       string
	Parameters []*Parameter
	ReturnType string

	// Body is set for an impl's method and nil for a trait's.
	Body *BlockStatement
}

func (tm *TraitMethod) String() string {
	var out bytes.Buffer
	out.WriteString("fn " + tm.Name + "(")
	for i, p := range tm.Parameters {
		if i > 0 {
			out.WriteString(", ")
		}
		out.WriteString(p.String())
	}
	out.WriteString(")")
	if tm.ReturnType != "" {
		out.WriteString(" -> " + tm.ReturnType)
	}
	if tm.Body != nil {
		out.WriteString(" " + tm.Body.String())
	}
	return out.String()
}

// ImplDecl is `impl Trait for Type { methods with bodies }`.
type ImplDecl struct {
	Token   token.Token // token.IMPL
	Trait   *Identifier
	Type    *Identifier
	Methods []*TraitMethod
}

func (id *ImplDecl) statementNode()       {}
func (id *ImplDecl) TokenLiteral() string { return id.Token.Literal }
func (id *ImplDecl) String() string {
	var out bytes.Buffer
	out.WriteString("impl " + id.Trait.String() + " for " + id.Type.String() + " { ")
	for i, m := range id.Methods {
		if i > 0 {
			out.WriteString("; ")
		}
		out.WriteString(m.String())
	}
	return out.String() + " }"
}

// ImplMethodName is the global name an impl's method is compiled under.
//
// The type and the method are both in it because variant-style names share one
// namespace: without the type, two types implementing the same trait would
// collide on the name and the second would silently replace the first.
//
// The separator is not a character a developer can type, so a hand-written
// function cannot collide with a generated one either.
func ImplMethodName(typeName, methodName string) string {
	return "\x00impl:" + typeName + "." + methodName
}

// IsImplFunctionName reports whether a name was generated by ImplMethodName.
//
// It exists so a diagnostic can tell "no such function" from "that name is
// internal", rather than printing a name containing a NUL byte.
func IsImplFunctionName(name string) bool {
	const prefix = "\x00impl:"
	return len(name) > len(prefix) && name[:len(prefix)] == prefix
}
